"""Real-data check of mtdi.fusion.Calibration on the UCI Air Quality dataset (uci-360, CC BY 4.0).

A metal-oxide CO sensor (PT08.S1, raw response) sat next to a certified reference analyser
(CO(GT), mg/m^3) in an Italian city for a year. We calibrate the cheap sensor against the
reference on the first 70 % of hours and test on the last 30 %, with and without temperature
compensation. Missing values in the source are -200 and are dropped, never filled.

    python tools/research/calibrate_air_quality.py path/to/AirQualityUCI.csv

Credit: De Vito, S. (2008). Air Quality. UCI Machine Learning Repository. https://doi.org/10.24432/C59K5F
Writes docs/results/air-quality-calibration.md with the numbers this run produced.
"""
import csv
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from mtdi.fusion import Calibration  # noqa: E402


def rows(path):
    with open(path, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f, delimiter=";"):
            try:
                ref, raw, t = (float(r[k].replace(",", ".")) for k in ("CO(GT)", "PT08.S1(CO)", "T"))
            except (KeyError, ValueError, AttributeError):
                continue
            if -200 in (ref, raw, t):
                continue
            yield raw, ref, t


def rmse(cal, data, use_t):
    return math.sqrt(sum((ref - cal.apply(raw, t if use_t else None)) ** 2 for raw, ref, t in data) / len(data))


def main(path):
    data = list(rows(path))
    cut = int(len(data) * 0.7)
    train, test = data[:cut], data[cut:]
    plain = Calibration.fit([d[0] for d in train], [d[1] for d in train])
    temp = Calibration.fit([d[0] for d in train], [d[1] for d in train], temperature=[d[2] for d in train])
    mean_ref = sum(d[1] for d in train) / len(train)
    baseline = math.sqrt(sum((d[1] - mean_ref) ** 2 for d in test) / len(test))
    lines = ["# Air-quality sensor calibration (real data)", "",
             "Dataset: UCI Air Quality (uci-360, CC BY 4.0), hourly, metal-oxide CO sensor vs reference analyser.",
             f"Usable hours after dropping missing values: {len(data)} (train {len(train)}, test {len(test)}, time-ordered split).", "",
             "| Model | gain | temp coeff | offset | test RMSE (mg/m³) |", "|---|---|---|---|---|",
             f"| predict the training mean (no sensor) | – | – | {mean_ref:.3f} | {baseline:.3f} |",
             f"| least squares | {plain.gain:.5f} | – | {plain.offset:.3f} | {rmse(plain, test, False):.3f} |",
             f"| least squares + temperature | {temp.gain:.5f} | {temp.temp_coeff:.4f} | {temp.offset:.3f} | {rmse(temp, test, True):.3f} |",
             "", "Generated by `tools/research/calibrate_air_quality.py`. Honest note: a linear model is the "
             "simplest calibration; metal-oxide sensors are non-linear and drift, which is what the ML work in "
             "S1-13 will improve on. The numbers above are measured, not claimed."]
    out = ROOT / "docs" / "results" / "air-quality-calibration.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
