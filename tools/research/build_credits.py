"""Write docs/CREDITS.md: every person, dataset, service and reference MTDI stands on.

Owner's rule: "every database, every data, every kilobyte needs to be acknowledged ... the
credits can be as long as possible." So this file is generated, never hand-pruned:

* people and organisations: the Inductra Vaion ISF report's acknowledgements (ops/inbox)
* datasets: registry/datasets.json (Research pillar), with licence and citation
* services and tools: registry/integrations.json, when present
* references: the ISF report's reference list, carried forward because MTDI grew out of it

    python tools/research/build_credits.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
ISF = ROOT / "ops" / "inbox" / "2026-10-21-isf-report-credits.md"
OUT = ROOT / "docs" / "CREDITS.md"


def isf_sections():
    paras = [p.strip() for p in ISF.read_text(encoding="utf-8").split("\n\n") if p.strip()]
    people, refs, mode = [], [], None
    for p in paras:
        if p == "Acknowledgments":
            mode = "people"
            continue
        if p == "References":
            mode = "refs"
            continue
        if mode == "people" and " — " in p:
            # The report speaks in the first person; this page speaks about the owner.
            people.append(re.sub(r"\s+", " ", p).replace("My parents", "Vaishnav's parents"))
        elif mode == "refs" and ("Available at" in p or re.search(r"\b(19|20)\d\d\.", p)):
            refs.append(p)
    return people, refs


def main():
    people, refs = isf_sections()
    datasets = json.loads((ROOT / "registry" / "datasets.json").read_text())["datasets"]
    integ = ROOT / "registry" / "integrations.json"
    services = json.loads(integ.read_text())["integrations"] if integ.exists() else []
    lines = ["# Credits", "",
             "MTDI 5 is built by Vaishnav Singh Hariparshad (NVTRA) with Claude Code as engineering director.",
             "It stands on the people, data, tools and research listed here. This page is generated by",
             "`tools/research/build_credits.py`; nothing is removed to keep it short.", "",
             "## People and organisations", "",
             "From the Inductra Vaion (MTDI 4) ISF report, Eskom Expo 2026, KZN Central:", ""]
    lines += [f"* {p}" for p in people]
    lines += ["", "## Datasets", "",
              f"{len(datasets)} datasets, catalogued with the licence read from each source. "
              "Simulated datasets are marked; MTDI never presents simulated data as measured.", "",
              "| Dataset | Provider | Licence | Origin | Citation |", "|---|---|---|---|---|"]
    for d in datasets:
        cite = d["credit"].replace("|", "/")
        lines.append(f"| [{d['name']}]({d['url']}) | {d['provider']} | {d['licence'] or 'not stated'} | {d['origin']} | {cite} |")
    if services:
        lines += ["", "## Services and tools", "", "| Service | Used for | Cost |", "|---|---|---|"]
        lines += [f"| {s['provider']} | {s['purpose']} | {s['cost']} |" for s in services]
    lines += ["", "## References carried from MTDI 4 (Inductra Vaion ISF report)", ""]
    lines += [f"* {r}" for r in refs]
    lines += ["", "## Generative AI", "",
              "Claude and Claude Code (Anthropic), ChatGPT and Codex (OpenAI), Gemini (Google), Grok (xAI) and Kimi "
              "(Moonshot AI) were used for research assistance, software, firmware and language editing, as disclosed "
              "in the ISF report. Engineering decisions are the owner's.", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(people)} people, {len(datasets)} datasets, "
          f"{len(services)} services, {len(refs)} references")


if __name__ == "__main__":
    main()
