"""Open MATLAB for a project, signed in with your own MathWorks account.

Writes a starter script that loads the project into the +mtdi toolbox, then:
  * with a desktop MATLAB installed and local=True: starts it in the project folder
    and runs the script;
  * otherwise: opens MATLAB Online in your browser. If the project is on GitHub, the
    "Open in MATLAB Online" link clones it into your MATLAB Drive and opens the script.
Your MathWorks sign-in happens in the browser; MTDI never sees it.
"""
import pathlib
import shutil
import subprocess
import urllib.parse
import webbrowser

ONLINE = "https://matlab.mathworks.com/"
OPEN_GITHUB = "https://matlab.mathworks.com/open/github/v1?repo={repo}&file={file}"


def starter(project, toolbox_rel, studio_url="http://127.0.0.1:8050"):
    meta = project["project"]
    lines = [f"%% {meta['name']} · MTDI 5.0 starter",
             "% Generated by `python -m mtdi matlab`. Run section by section (Ctrl+Enter).",
             f"here = fileparts(mfilename('fullpath'));",
             f"addpath(fullfile(here, '{toolbox_rel}'));",
             f"manifest = fullfile(here, 'project.json');",
             "",
             "%% Live: read the running studio (python -m mtdi run <project>)",
             f"% p = mtdi.packet('{studio_url}');",
             f"% mtdi.watch('{studio_url}', 60);",
             "",
             "%% Recorded: summarise a session (python -m mtdi run <project> --record session.jsonl)",
             "% s = mtdi.analyze(fullfile(here, 'session.jsonl'), manifest)",
             "",
             "%% Two implementations, one capture",
             "% system('python -m mtdi analyze <project> session.jsonl > py.json');",
             "% mtdi.verify(fullfile(here, 'session.jsonl'), manifest, fullfile(here, 'py.json'))",
             "",
             "%% Channels in this project"]
    for ch in project["channels"]:
        lines.append(f"% {ch['id']}: {ch['label']} [{ch['unit'] or '-'}] keys {', '.join(ch['keys'])}")
    return "\n".join(lines) + "\n"


def open_project(project, repo=None, local=False, dry_run=False):
    folder = pathlib.Path(project["_dir"])
    root = folder
    while root != root.parent and not (root / "matlab" / "+mtdi").exists() and not (root / "mtdi-matlab" / "+mtdi").exists():
        root = root.parent
    toolbox = root / "matlab" if (root / "matlab" / "+mtdi").exists() else root / "mtdi-matlab"
    rel = pathlib.Path(*([".."] * len(folder.relative_to(root).parts))) / toolbox.name if root != folder else pathlib.Path(toolbox.name)
    script = folder / f"start_{project['project']['id'].replace('-', '_')}.m"
    plan = {"script": str(script)}
    exe = shutil.which("matlab")
    if local and exe:
        plan["launch"] = [exe, "-sd", str(folder), "-r", f"run('{script.name}')"]
    elif repo:
        try:
            rel_file = script.relative_to(root).as_posix()
        except ValueError:
            rel_file = script.name
        plan["open"] = OPEN_GITHUB.format(repo=urllib.parse.quote(repo, safe="/"), file=urllib.parse.quote(rel_file, safe="/"))
    else:
        plan["open"] = ONLINE
        plan["note"] = "Upload the project folder to MATLAB Drive, then run the starter script."
    if dry_run:
        return dict(plan, dry_run=True)
    script.write_text(starter(project, rel.as_posix()), encoding="utf-8")
    if "launch" in plan:
        subprocess.Popen(plan["launch"])
    else:
        webbrowser.open(plan["open"], new=2)
    return plan
